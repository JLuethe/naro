#!/usr/bin/env python3
"""Generate the binding tables appendix of 02-keybindings.md from
data/keybindings.csv and data/helplines-80cols.csv.

Reference revision: 6ed285c3ec7a1d228def4d4e7021c6ba269f620c

Writes spec/02-keybindings-tables.md (included by reference from
02-keybindings.md).  Re-run after build_inventories.py.
"""
import csv
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
SPEC = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

ORDER = ["MMAIN", "MWHEREIS", "MREPLACE", "MREPLACEWITH", "MGOTOLINE", "MWRITEFILE",
         "MINSERTFILE", "MEXECUTE", "MSPELL", "MLINTER", "MYESNO", "MHELP", "MFINDINHELP",
         "MBROWSER", "MWHEREISFILE", "MGOTODIR"]
TITLE = {
    "MMAIN": "Main edit window (`main`)", "MWHEREIS": "Search prompt (`search`)",
    "MREPLACE": "Search-to-replace prompt (`replace`)", "MREPLACEWITH": "Replace-with prompt (`replacewith`)",
    "MGOTOLINE": "Go-to-line prompt (`gotoline`)", "MWRITEFILE": "Write-file prompt (`writeout`)",
    "MINSERTFILE": "Insert-file prompt (`insert`)", "MEXECUTE": "Execute-command prompt (`execute`)",
    "MSPELL": "Spell-correction prompt (`spell`)", "MLINTER": "Linter navigation (`linter`)",
    "MYESNO": "Yes/No questions (`yesno`)", "MHELP": "Help viewer (`help`)",
    "MFINDINHELP": "Search prompt inside the help viewer (no rc name)",
    "MBROWSER": "File browser (`browser`)", "MWHEREISFILE": "Browser search prompt (`whereisfile`)",
    "MGOTODIR": "Browser go-to-directory prompt (`gotodir`)",
}

INPUT = {  # input bytes in ENV-BASE (tmux-256color, keypad transmit mode on)
    "Up": "ESC O A", "Down": "ESC O B", "Left": "ESC O D", "Right": "ESC O C",
    "▴": "ESC O A", "▾": "ESC O B", "◂": "ESC O D", "▸": "ESC O C",
    "Home": "ESC [ 1 ~", "End": "ESC [ 4 ~", "PgUp": "ESC [ 5 ~", "PgDn": "ESC [ 6 ~",
    "Ins": "ESC [ 2 ~", "Del": "ESC [ 3 ~", "Bsp": "0x7F", "Enter": "keypad Enter: ESC O M",
    "Tab": "0x09", "Sh-Tab": "ESC [ Z", "Space": "0x20", "Sh-Del": "ESC [ 3 ; 2 ~ (decoded by nano)",
    "^Home": "ESC [ 1 ; 5 H", "^End": "ESC [ 1 ; 5 F", "^Del": "ESC [ 3 ; 5 ~",
    "Sh-^Del": "ESC [ 3 ; 6 ~", "M-Bsp": "ESC 0x7F (or kDC6)", "M-Del": "ESC [ 3 ; 3 ~",
    "M-Ins": "ESC [ 2 ; 3 ~", "M-Home": "ESC [ 1 ; 3 H", "M-End": "ESC [ 1 ; 3 F",
    "M-PgUp": "ESC [ 5 ; 3 ~", "M-PgDn": "ESC [ 6 ; 3 ~",
    "^Left": "ESC [ 1 ; 5 D", "^Right": "ESC [ 1 ; 5 C", "^Up": "ESC [ 1 ; 5 A", "^Down": "ESC [ 1 ; 5 B",
    "^◂": "ESC [ 1 ; 5 D", "^▸": "ESC [ 1 ; 5 C", "^▴": "ESC [ 1 ; 5 A", "^▾": "ESC [ 1 ; 5 B",
    "M-Left": "ESC [ 1 ; 3 D", "M-Right": "ESC [ 1 ; 3 C", "M-Up": "ESC [ 1 ; 3 A", "M-Down": "ESC [ 1 ; 3 B",
    "M-◂": "ESC [ 1 ; 3 D", "M-▸": "ESC [ 1 ; 3 C", "M-▴": "ESC [ 1 ; 3 A", "M-▾": "ESC [ 1 ; 3 B",
    "^Space": "0x00", "M-Space": "ESC 0x20",
}
FKEYS = {1: "ESC O P", 2: "ESC O Q", 3: "ESC O R", 4: "ESC O S", 5: "ESC [ 1 5 ~", 6: "ESC [ 1 7 ~",
         7: "ESC [ 1 8 ~", 8: "ESC [ 1 9 ~", 9: "ESC [ 2 0 ~", 10: "ESC [ 2 1 ~", 11: "ESC [ 2 3 ~",
         12: "ESC [ 2 4 ~"}


def input_bytes(key, code):
    if key in INPUT:
        return INPUT[key]
    if key.startswith("F") and key[1:].isdigit():
        return FKEYS.get(int(key[1:]), "kf%s" % key[1:])
    if key.startswith("^") and len(key) == 2:
        c = key[1]
        if c == "/":
            return "0x1F"
        if c == "-":
            return "0x1F (Linux console)"
        return "0x%02X" % (ord(c.upper()) & 0x1F)
    if key.startswith("M-") and len(key) == 3:
        c = key[2]
        b = ord(c.lower()) if c.isalpha() else ord(c)
        return "ESC 0x%02X ('%s')" % (b, chr(b))
    if key == "":
        return "(internal code only)"
    return ""


def main():
    rows = list(csv.DictReader(open(os.path.join(SPEC, "data", "keybindings.csv"), encoding="utf-8")))
    hl = list(csv.DictReader(open(os.path.join(SPEC, "data", "helplines-80cols.csv"), encoding="utf-8")))
    out = []
    out.append("# 02 (appendix) — Default binding tables\n")
    out.append("Reference commit: `6ed285c3ec7a1d228def4d4e7021c6ba269f620c`\n")
    out.append("Generated by `tools/gen_key_tables.py` from `data/keybindings.csv` (gdb dumps of the\n"
               "unmodified reference executables) — do not edit by hand.  Requirements that\n"
               "govern these tables are in `02-keybindings.md`.\n")
    out.append("Columns: **Key** = notation shown in help lines (UTF-8 locale); **Input (ENV-BASE)** = bytes\n"
               "the key sends in tmux-256color; **Function** = rc function name(s) (C symbol); **Tag** =\n"
               "help-line label in this context; **Profiles** = which dumped profiles contain the binding\n"
               "(`all-default` = every default-build profile, `+tiny` = also every tiny profile); **Condition**\n"
               "= build condition / runtime condition at registration; **Src** = `src/global.c` line.\n"
               "Order within a context is the lookup order: the first matching row wins.\n")
    allprof = {p for r in rows for p in r["profiles"].split()}
    defprof = {p for p in allprof if p.startswith("default")}
    tinyprof = {p for p in allprof if p.startswith("tiny")}
    for ctx in ORDER:
        rs = [r for r in rows if r["context"] == ctx]
        out.append("\n## %s\n" % TITLE[ctx])
        hlrow = [h for h in hl if h["profile"] == "default-utf8" and h["context"] == ctx]
        if hlrow:
            hlrow.sort(key=lambda h: int(h["slot"]))
            out.append("Help lines at 80 columns (default profile): " +
                       ", ".join("`%s %s`" % (h["key_display"], h["help_tag"]) for h in hlrow) + "\n")
        if ctx == "MYESNO":
            out.append("Besides the rows below, the Yes/No dispatcher handles letters and ^Y/^N/^A/^Q itself — see KEY-YESNO.\n")
        out.append("| # | Key | Input (ENV-BASE) | Function | Tag | Profiles | Condition | Src |")
        out.append("|---|---|---|---|---|---|---|---|")
        for n, r in enumerate(sorted(rs, key=lambda r: int(r["source"].split(":")[1])), 1):
            profs = set(r["profiles"].split())
            if profs >= defprof and profs >= tinyprof:
                ptxt = "all-default +tiny"
            elif profs >= defprof:
                ptxt = "all-default"
            else:
                ptxt = " ".join(sorted(profs))
            fn = r["rc_function_names"] or "—"
            if r["toggle_flag"]:
                fn = "%s (toggle %s)" % (fn, r["toggle_flag"])
            fn += " (`%s`)" % r["function_c"]
            cond = "; ".join(x for x in (r["build_condition"], r["runtime_condition"]) if x)
            key = r["key_display"] if r["key_display"] else "*(none: %s)*" % r["keycode_symbol"]
            out.append("| %d | `%s` | %s | %s | %s | %s | %s | %s |" % (
                n, key.replace("|", "\\|").replace("`", "'") if key.startswith("*") is False else key,
                input_bytes(r["key_display"], int(r["keycode"])), fn, r["help_tag"] or "", ptxt,
                cond.replace("|", "\\|"), r["source"].split(":")[1]))
    # profile difference summary
    out.append("\n## Profile differences (relative to default-utf8)\n")
    out.append("Computed from the dumps; each line lists bindings present (+) or absent (−).\n")
    import json
    tables = os.path.join(SPEC, "evidence", "tables")
    base = json.load(open(os.path.join(tables, "default-utf8.json")))
    keyset = lambda d: {(k["keystr"], k["func"], tuple(k["menus"])) for k in d["keys"]}
    b = keyset(base)
    for prof in ("default-C", "default-modern", "default-modern-vt220", "default-preserve",
                 "default-restricted", "default-view", "default-saveonexit"):
        s = keyset(json.load(open(os.path.join(tables, prof + ".json"))))
        out.append("\n### %s\n" % prof)
        if s == b:
            out.append("No difference.\n")
            continue
        for x in sorted(s - b, key=str):
            out.append("- \\+ `%s` → %s in %s" % (x[0], x[1], ", ".join(x[2])))
        for x in sorted(b - s, key=str):
            out.append("- − `%s` → %s in %s" % (x[0], x[1], ", ".join(x[2])))
    open(os.path.join(SPEC, "02-keybindings-tables.md"), "w", encoding="utf-8").write("\n".join(out) + "\n")
    print("wrote 02-keybindings-tables.md")


if __name__ == "__main__":
    main()
